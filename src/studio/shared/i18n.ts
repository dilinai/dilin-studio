// 底座字串（繁中／简中／英文）＋取字函数＋语言偏好。
//   编辑器自己的字串放 <app>/i18n.ts，格式同 StudioDict；画面里用 useStudioT()（见 StudioT.tsx）。
//   语言来源：localStorage「dilin-studio-lang」＞ host.defaultLang()（站别：简体站简中、其余繁中）。
//   host.langLocked() 为真（简体站）⇒ 恒用 defaultLang、不显示切换（与网站本体同一规矩）。

import type { StudioDict, StudioLang, StudioT } from './types'
import { STUDIO_LANGS } from './types'
import { defaultLang, langLocked } from './host'
import { STUDIO_COMPONENT_I18N, type StudioComponentKey } from './components/i18n'

export const STUDIO_LANG_STORAGE_KEY = 'dilin-studio-lang'

export const STUDIO_LANG_LABELS: Record<StudioLang, string> = { 'zh-TW': '繁體中文', 'zh-CN': '简体中文', en: 'English' }

export function isStudioLang(x: unknown): x is StudioLang {
  return typeof x === 'string' && (STUDIO_LANGS as readonly string[]).includes(x)
}

/** 现在该用哪种语言（只在浏览器读 localStorage；服务端／单测回 host 默认）。 */
export function resolveStudioLang(): StudioLang {
  const def = defaultLang()
  if (langLocked()) return def
  try {
    const v = typeof localStorage !== 'undefined' ? localStorage.getItem(STUDIO_LANG_STORAGE_KEY) : null
    if (isStudioLang(v)) return v
  } catch { /* 隐私模式读不到 ⇒ 用默认 */ }
  return def
}
export function saveStudioLang(lang: StudioLang): void {
  try { localStorage.setItem(STUDIO_LANG_STORAGE_KEY, lang) } catch { /* 存不了就算了 */ }
}

/** {name} 形占位代入；没给的占位原样留着。 */
export function fillVars(s: string, vars?: Record<string, string | number>): string {
  if (!vars) return s
  return s.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m))
}

/**
 * 把几张字典叠成一个取字函数：后面的字典盖前面的；本语言没有 ⇒ 退英文 ⇒ 退键名。
 * 例：makeStudioT([STUDIO_SHARED_I18N, SHEETS_I18N], 'zh-TW')
 */
export function makeStudioT(dicts: readonly StudioDict[], lang: StudioLang): StudioT {
  const pick = (key: string): string | undefined => {
    for (let i = dicts.length - 1; i >= 0; i--) { const v = dicts[i][lang]?.[key]; if (v !== undefined) return v }
    for (let i = dicts.length - 1; i >= 0; i--) { const v = dicts[i].en?.[key]; if (v !== undefined) return v }
    return undefined
  }
  return (key, vars) => fillVars(pick(key) ?? key, vars)
}

/** 检查一张字典三语键是否齐（给各编辑器的题用）：回缺的「语言:键」清单。 */
export function missingKeys(dict: StudioDict): string[] {
  const all = new Set<string>()
  for (const l of STUDIO_LANGS) for (const k of Object.keys(dict[l] ?? {})) all.add(k)
  const out: string[] = []
  for (const l of STUDIO_LANGS) for (const k of all) if (!(k in (dict[l] ?? {}))) out.push(`${l}:${k}`)
  return out
}

